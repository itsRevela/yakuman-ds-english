"""Generate asm/name_entry.asm: an English-first layout for the name-entry keyboard.

The keyboard is 4 pages x 65 key pointers at 0x0210C87C (page stride 0x104; the last 5 slots of the
on-screen grid are the graphic Space/Back/OK buttons). Each pointer names a one-character
full-width string (0 = blank key). The original pages are hiragana, katakana, Latin letters,
digits/symbols; page 0 is shown first. The new layout is Latin letters (default), digits/symbols,
hiragana, katakana.
Every character used already exists as a key string in the original table, so only the pointers
change (names stay full-width, which the 3D name font requires).

L/R move to page-1 / page+1 (mod 4); the page tab graphics are redrawn separately.
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

from romdata import ARM9_BASE, ROOT, load_arm9

TABLE = 0x0210C87C
KEYS_PER_PAGE = 65
PAGES = 4
OUT = ROOT / "asm" / "name_entry.asm"

LATIN = (
    "ＡＢＣＤＥＦＧＨＩＪ"
    "ＫＬＭＮＯＰＱＲＳＴ"
    "ＵＶＷＸＹＺ’！？＆"
    "ａｂｃｄｅｆｇｈｉｊ"
    "ｋｌｍｎｏｐｑｒｓｔ"
    "ｕｖｗｘｙｚー～％＄"
    "　　　　　"
)
GAP = "　"  # full-width space in LATIN marks a blank key


def read_original(a9: bytes) -> list[list[int]]:
    pages = []
    for p in range(PAGES):
        base = TABLE + p * KEYS_PER_PAGE * 4 - ARM9_BASE
        pages.append([struct.unpack_from("<I", a9, base + i * 4)[0] for i in range(KEYS_PER_PAGE)])
    return pages


def char_addresses(a9: bytes, pages: list[list[int]]) -> dict[str, int]:
    out: dict[str, int] = {}
    for page in pages:
        for ptr in page:
            if ptr:
                off = ptr - ARM9_BASE
                ch = a9[off : a9.index(b"\x00", off)].decode("cp932")
                out.setdefault(ch, ptr)
    return out


def build_layout(pages: list[list[int]], addrs: dict[str, int]) -> list[list[int]]:
    if len(LATIN) != KEYS_PER_PAGE:
        raise ValueError(f"Latin page has {len(LATIN)} keys, expected {KEYS_PER_PAGE}")
    missing = sorted({c for c in LATIN if c != GAP and c not in addrs})
    if missing:
        raise ValueError(f"no existing key string for {missing}")
    latin = [0 if c == GAP else addrs[c] for c in LATIN]
    hiragana, katakana, numbers = pages[0], pages[1], pages[3]
    return [latin, numbers, hiragana, katakana]


def render(layout: list[list[int]]) -> str:
    lines = [
        "; GENERATED by tools/gen_keyboard.py - do not edit by hand.",
        "; Name-entry keyboard: page 0 Latin (default), 1 digits/symbols, 2 hiragana, 3 katakana.",
        f".org 0x{TABLE:08X}",
    ]
    for p, page in enumerate(layout):
        lines.append(f"; page {p}")
        for i in range(0, KEYS_PER_PAGE, 5):
            lines.append("    .word " + ", ".join(f"0x{v:08X}" for v in page[i : i + 5]))
    return "\n".join(lines) + "\n"


def main() -> int:
    a9 = load_arm9()
    pages = read_original(a9)
    OUT.write_text(render(build_layout(pages, char_addresses(a9, pages))), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
